import struct, sys
d = open(sys.argv[1], "rb").read()
nsec, symtab, nsym = struct.unpack_from("<H", d, 2)[0], *struct.unpack_from("<II", d, 8)
text = []
for i in range(nsec):
    o = 20 + 40 * i
    if d[o:o + 5] == b".text":
        size, raw, _, _, nrel = struct.unpack_from("<IIIIH", d, o + 16)
        if nrel: 
            sys.exit("cave.obj's code needs relocations")
            
        text.append((i + 1, d[raw:raw + size]))
if len(text) != 1: sys.exit("expected one code section, found %d" % len(text))
syms, i = {}, 0
while i < nsym:
    o = symtab + 18 * i
    name, value, sec, _, _, naux = struct.unpack_from("<8sIhHBB", d, o)
    if sec == text[0][0]:
        if name[:4] == b"\0\0\0\0":
            s = symtab + 18 * nsym + struct.unpack_from("<I", name, 4)[0]
            name = d[s:d.index(b"\0", s)]
        syms[name.rstrip(b"\0").decode()] = value
    i += 1 + naux
b = text[0][1]
with open(sys.argv[2], "w") as f:
    f.write("// generated by gen_cave.py from cave.c\n")
    f.write("static const unsigned kRemoteVisit = 0x%x, kLaserRecord = 0x%x;\n" % (syms["RemoteVisit"], syms["LaserRecord"]))
    f.write("static const unsigned char kCaveCode[] = {\n")
    for k in range(0, len(b), 20): f.write("  " + ",".join("0x%02x" % x for x in b[k:k + 20]) + ",\n")
    f.write("};\n")
print("cave code: %d bytes" % len(b))
